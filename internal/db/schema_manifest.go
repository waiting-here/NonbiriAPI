// PinnedGenerationTwoSchemaHash makes an intentional DDL change explicit.
// It is derived from the canonical Generation 2 DDL and is checked before a
// database is opened for writing.
const PinnedGenerationTwoSchemaHash = "5067991d905ac3a601ed8c3fd00938386e5b1605a56edc55650b668dc0601cc1"

// PinnedGenerationTwoManifestHash is an independently checked-in fixture for
// the complete sqlite_schema/table_xinfo/foreign-key/index manifest.  It is
// deliberately not generated by executing the DDL constant at runtime:
// changing one DDL object without updating this fixture must fail closed.
const PinnedGenerationTwoManifestHash = "13cbf2f85797b365b7e79334bfb12288274587b9dc7e143316b5412ce18eb68f"

const generationTwoManifestFixture = `{"sha256":"13cbf2f85797b365b7e79334bfb12288274587b9dc7e143316b5412ce18eb68f"}`

// PinnedGenerationTwoFreshConfigSeedHash is an independently checked-in
// golden for the complete fresh site_config row set.  Unlike the current
// seed validator, this golden is intentionally not derived from the runtime
// configuration catalog or its INSERT helper.  The announcement epoch is
// generated per database and is canonicalized to a fixed marker before this
// digest is calculated; every other key, value, and updated_at is covered
// byte-for-byte by the ordered row digest.
const PinnedGenerationTwoFreshConfigSeedHash = "c211e1ba99e0f273022165c417b9c0a419bf9c7e863596db3e9bed3562dfefdd"

const generationTwoFreshConfigSeedFixture = `{"sha256":"c211e1ba99e0f273022165c417b9c0a419bf9c7e863596db3e9bed3562dfefdd"}`

const generationTwoFreshConfigEpochMarker = "<generated:b1e_>"

type queryer interface {
	QueryContext(context.Context, string, ...any) (*sql.Rows, error)
	QueryRowContext(context.Context, string, ...any) *sql.Row
}

type schemaObject struct {
	Type, Name, Table, SQL string
}

type columnManifest struct {
	CID, NotNull, PrimaryKey, Hidden int
	Name, Type                       string
	Default                          sql.NullString
}

type foreignKeyManifest struct {
	ID, Sequence                               int
	Table, From, To, OnUpdate, OnDelete, Match string
}

type indexManifest struct {
	Name            string
	Unique, Partial int
	Origin          string
	Columns         []indexColumnManifest
}

type indexColumnManifest struct {
	Sequence, CID, Descending, Key int
	Name                           sql.NullString
	Collation                      string
}

type tableManifest struct {
	Name        string
	Columns     []columnManifest
	ForeignKeys []foreignKeyManifest
	Indexes     []indexManifest
}

type generationManifest struct {
	Objects []schemaObject
	Tables  []tableManifest
}

// generationTwoSeedManifest is intentionally independent from the structural
// schema manifest.  SQLite's sqlite_schema cannot prove that the required
// bootstrap rows (or their exact key set) exist, and a structural match must
// never make a partially seeded database writable.
type generationTwoSeedAccount struct {
	Code string
	Kind string
}

type generationTwoSeedPool struct {
	IDPrefix      string
	PoolType      string
	State         string
	Revision      int64
	AccountKind   string
	AccountPrefix string
	PeriodIsNull  bool
}

type generationTwoSeedManifest struct {
	ConfigKeys            []string
	ConfigRevisionDomains []string
	FixedAccounts         []generationTwoSeedAccount
	InitialPools          []generationTwoSeedPool
	SingletonRows         []string
}

type generationTwoFreshConfigSeedRow struct {
	Key       string `json:"key"`
	Value     string `json:"value"`
	UpdatedAt int64  `json:"updated_at"`
}

