function charityRoleSource(key) {
  const donationFields = [
    'allStatuses',
    'noDonations',
    'noDonationsBody',
    'saveKeyLimits',
    'statusFilter',
  ];
  const field = key.split('.').at(-1);
  const priceFields = [
    'discountEnabled',
    'discountEnd',
    'discountPercent',
    'discountStart',
    'perRequest',
    'perToken',
    'pricingMode',
    'request_donor_reward_milli',
    'request_user_price_milli',
  ];
  return donationFields.includes(field)
    ? charityManagement
    : priceFields.includes(field)
      ? charityPriceFields
      : charityModels;
}
