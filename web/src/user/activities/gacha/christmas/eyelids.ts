// Each column records the eye opening and the painted upper lash in source pixels.
// Closed art contributes only inside that opening; brows, cheeks and bangs stay in the original art.
type EyeColumn = readonly [
  x: number,
  top: number,
  bottom: number,
  upper: number,
  lower: number,
  closedUpper: number,
  closedLower: number,
  coverage: number,
];
type EyePair = readonly [EyelidProfile, EyelidProfile];
function profile(
  box: readonly [number, number, number, number],
  columns: readonly EyeColumn[],
  registered = false,
  openingPadding = 0,
): EyelidProfile {
  const [left, top, right, bottom] = box;
  const rows: [number[], number[]] = [[], []];
  const encode = (y: number) =>
    Math.round(Math.max(0, Math.min(1, (y - top) / (bottom - top))) * 255);
  for (let i = 0; i < eyelidProfileWidth; i++) {
    const x = left + ((right - left) * i) / (eyelidProfileWidth - 1);
    let j = 1;
    while (j < columns.length - 1 && columns[j][0] < x) j++;
    const a = columns[j - 1],
      b = columns[j];
    const t = Math.max(0, Math.min(1, (x - a[0]) / (b[0] - a[0])));
    const sample = (channel: number) => a[channel] + (b[channel] - a[channel]) * t;
    rows[0].push(
      encode(sample(1) - openingPadding),
      encode(sample(2) + openingPadding),
      encode(sample(3)),
      encode(sample(4)),
    );
    rows[1].push(encode(sample(5)), encode(sample(6)), Math.round(sample(7) * 255), 255);
  }
  return {
    bounds: [
      (registered ? left : 51.2 + left * 0.9) / 1024,
      (registered ? top : 76.8 + top * 0.9) / 1536,
      ((right - left) * (registered ? 1 : 0.9)) / 1024,
      ((bottom - top) * (registered ? 1 : 0.9)) / 1536,
    ],
    rows,
  };
}

