import type { ChristmasCard, ChristmasRig, Point, RibSection } from './motion';

const place = ([x, y]: Point): Point => [51.2 + x * 0.9, 76.8 + y * 0.9];
function registered(rig: ChristmasRig): ChristmasRig {
  return {
    ribs: rig.ribs.map(([y, left, right, lift, expansion, follow]): RibSection => [
      76.8 + y * 0.9,
      51.2 + left * 0.9,
      51.2 + right * 0.9,
      lift * 0.9,
      expansion,
      follow,
    ]),
    feather: rig.feather * 0.9,
    materials: rig.materials.map((region) => ({
      ...region,
      polygon: region.polygon.map(place),
      root: place(region.root),
      tip: place(region.tip),
      amplitude: [region.amplitude[0] * 0.9, region.amplitude[1] * 0.9],
      feather: region.feather * 0.9,
    })),
    fixed: rig.fixed.map((polygon) => polygon.map(place)),
    floating: rig.floating && {
      polygon: rig.floating.polygon.map(place),
      amplitude: [rig.floating.amplitude[0] * 0.9, rig.floating.amplitude[1] * 0.9],
    },
  };
}

